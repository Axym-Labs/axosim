"""Explicit full-sequence execution for independently supplied Mamba histories."""

from __future__ import annotations

from dataclasses import dataclass

import torch

from axosim.mamba_official import BranchOfficialMamba
from axosim.mamba_pytorch import MambaBlock


@dataclass(frozen=True)
class HistoryScanBackend:
    """Execution path selected without replacing or modifying the model."""

    name: str
    parallel: bool
    reason: str


@dataclass(frozen=True)
class HistoryScanResult:
    """Predictions and the execution path used for the complete histories."""

    prediction: torch.Tensor
    backend: HistoryScanBackend


def scan_histories(
    model: BranchOfficialMamba,
    inputs: torch.Tensor,
    *,
    morphology_indices: torch.Tensor | None = None,
    neuron_batch_size: int | None = None,
    require_parallel: bool = True,
) -> HistoryScanResult:
    """Evaluate supplied ``(neurons, time, input_channels)`` histories.

    ``inputs.shape[-1]`` must equal ``model.num_input``. Use one neuron for a
    single-neuron history or multiple neurons sharing the same model weights.
    ``neuron_batch_size`` partitions only the neuron dimension; each partition
    receives its complete time sequence and matching morphology indices.

    The default requires official Mamba1's CUDA full-sequence fused fast path.
    The portable PyTorch Mamba reference is sequential and must be explicitly
    permitted with ``require_parallel=False``, even on CUDA. This option does
    not substitute backends or make official CUDA checkpoints CPU-compatible.

    Autograd and the caller's train/eval mode are preserved. For inference,
    callers can use ``model.eval()`` and ``torch.inference_mode()``. Each call
    starts a fresh history; streaming continuation uses the separate streaming
    API. Future recurrent contact events must already be supplied and are not
    generated by this function.
    """
    if not isinstance(model, BranchOfficialMamba):
        raise TypeError("scan_histories requires an AxoSim or Branch-routed Mamba model")
    if not isinstance(inputs, torch.Tensor):
        raise TypeError("inputs must be a torch.Tensor")
    if inputs.ndim != 3:
        raise ValueError("inputs must have shape (neurons, time, input_channels)")
    if inputs.shape[0] == 0 or inputs.shape[1] == 0:
        raise ValueError("inputs must have non-empty neuron and time dimensions")
    if inputs.shape[2] != model.num_input:
        raise ValueError(f"inputs must have num_input={model.num_input} channels")
    if not inputs.is_floating_point():
        raise ValueError("inputs must have a floating-point dtype")
    if neuron_batch_size is not None and (
        isinstance(neuron_batch_size, bool)
        or not isinstance(neuron_batch_size, int)
        or neuron_batch_size <= 0
    ):
        raise ValueError("neuron_batch_size must be a positive integer or None")
    if not isinstance(require_parallel, bool):
        raise TypeError("require_parallel must be a bool")
    if any(parameter.device != inputs.device for parameter in model.parameters()):
        raise ValueError("inputs and model parameters must be on the same device")

    _validate_morphology(model, morphology_indices, inputs.shape[0])
    backend = _select_backend(model, inputs, require_parallel=require_parallel)
    chunk_size = neuron_batch_size or inputs.shape[0]
    predictions = []
    for start in range(0, inputs.shape[0], chunk_size):
        stop = start + chunk_size
        predictions.append(
            model(
                inputs[start:stop],
                morphology_indices=(
                    None if morphology_indices is None else morphology_indices[start:stop]
                ),
            )
        )
    prediction = predictions[0] if len(predictions) == 1 else torch.cat(predictions, dim=0)
    return HistoryScanResult(prediction=prediction, backend=backend)


def _validate_morphology(
    model: BranchOfficialMamba,
    indices: torch.Tensor | None,
    neurons: int,
) -> None:
    ids = model.config.morphology_ids
    if ids is None:
        if indices is not None:
            raise ValueError("morphology_indices were provided to an unconditioned model")
        return
    if indices is None:
        raise ValueError("morphology_indices are required for a morphology-conditioned model")
    if not isinstance(indices, torch.Tensor) or indices.ndim != 1 or indices.shape[0] != neurons:
        raise ValueError("morphology_indices must have shape (neurons,)")
    if indices.dtype not in {torch.uint8, torch.int8, torch.int16, torch.int32, torch.int64}:
        raise ValueError("morphology_indices must have an integer dtype")
    if bool((indices < 0).any()) or bool((indices >= len(ids)).any()):
        raise ValueError(f"morphology_indices must be in range [0, {len(ids)})")


def _select_backend(
    model: BranchOfficialMamba,
    inputs: torch.Tensor,
    *,
    require_parallel: bool,
) -> HistoryScanBackend:
    if model.config.block_type != "mamba1":
        raise RuntimeError("scan_histories currently supports only the Mamba1 history backend")
    blocks = [block.mamba for block in model.blocks]
    if blocks and all(type(block) is MambaBlock for block in blocks):
        if require_parallel:
            raise RuntimeError(
                "require_parallel=True rejects the sequential PyTorch Mamba reference; "
                "use an official CUDA Mamba model or explicitly set require_parallel=False"
            )
        return HistoryScanBackend(
            name="pytorch-sequential-reference",
            parallel=False,
            reason="Portable PyTorch Mamba evaluates the state recurrence sequentially in time.",
        )

    try:
        from mamba_ssm.modules import mamba_simple
        from mamba_ssm.ops import selective_scan_interface
    except ImportError as error:
        raise RuntimeError("The official Mamba1 fused CUDA backend is unavailable") from error
    if not blocks or any(type(block) is not mamba_simple.Mamba for block in blocks):
        raise RuntimeError("The model does not contain the supported official Mamba1 blocks")
    if inputs.device.type != "cuda":
        raise RuntimeError(
            "Official Mamba1 history scan requires CUDA inputs and model; "
            "require_parallel=False does not replace checkpoint backends"
        )
    if inputs.dtype not in {torch.float16, torch.bfloat16, torch.float32}:
        raise ValueError("Official Mamba1 scan requires float16, bfloat16 or float32 inputs")
    if any(not block.use_fast_path for block in blocks):
        raise RuntimeError("Official Mamba1 history scan requires use_fast_path=True in every block")
    if (
        mamba_simple.causal_conv1d_fn is None
        or not callable(mamba_simple.mamba_inner_fn)
        or selective_scan_interface.causal_conv1d_fwd_function is None
        or selective_scan_interface.causal_conv1d_bwd_function is None
        or not callable(selective_scan_interface.selective_scan_cuda.fwd)
        or not callable(selective_scan_interface.selective_scan_cuda.bwd)
    ):
        raise RuntimeError("Official Mamba1 fused selective-scan or causal-convolution kernels are unavailable")
    return HistoryScanBackend(
        name="official-mamba1-fused",
        parallel=True,
        reason="Official Mamba1 full-sequence mamba_inner_fn with fused CUDA selective scan and causal convolution.",
    )
